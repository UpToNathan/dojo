#!/usr/bin/env bash
# Asks the mesh which peers offer a Nix cache and records the ones you approve in
# /etc/nix/dojo-cache.conf, which system-config/nix/nix.conf includes.
#
# A cache's signing key is trusted by Nix for every package it serves, so a peer's key is never
# trusted just because it appeared: a new or changed key is shown and needs your yes (or --yes).
# Peers that are offline or gone are kept; --prune rebuilds the file from the peers that answer now.
set -euo pipefail

target=${DOJO_NIX_CACHE_CONF:-/etc/nix/dojo-cache.conf}
yes=false
prune=false
for argument in "$@"; do
    case $argument in
        --yes) yes=true ;;
        --prune) prune=true ;;
        *) echo "Usage: $0 [--yes] [--prune]" >&2; exit 2 ;;
    esac
done

# DOJO_AS_ROOT lets the tests write somewhere they own.
as_root() {
    if [[ -n ${DOJO_AS_ROOT:-} ]]; then "$DOJO_AS_ROOT" "$@"
    elif [[ $EUID -eq 0 ]]; then "$@"
    else sudo "$@"; fi
}

data_home=${XDG_DATA_HOME:-"$HOME/.local/share"}
mesh=${DOJO_MESH:-"$data_home/dojo/bin/dojo-mesh"}
[[ -x $mesh ]] || mesh=$(command -v dojo-mesh || true)
[[ -n $mesh ]] || { echo "dojo-mesh is not installed; run scripts/install-helpers.sh dojo-mesh" >&2; exit 1; }

declare -A approved=()     # host -> "port key", what the file says now
if [[ -r $target ]]; then
    while read -r hash word host port key _; do
        [[ $hash == '#' && $word == peer && -n $key ]] && approved[$host]="$port $key"
    done < "$target"
fi

declare -A offered=()      # host -> "port key", what the mesh says now
status=0
lines=$("$mesh" find nix-cache --peers-only --tsv) || status=$?
if (( status > 1 )); then
    echo "Could not ask the mesh (dojo-mesh find exited $status)." >&2
    exit 1
fi
while IFS=$'\t' read -r -a fields; do
    (( ${#fields[@]} >= 2 )) || continue
    host=${fields[1]} port='' key=''
    for field in "${fields[@]:2}"; do
        case $field in
            port=*) port=${field#port=} ;;
            public-key=*) key=${field#public-key=} ;;
        esac
    done
    if [[ ! $host =~ ^[A-Za-z0-9.-]+$ || ! $port =~ ^[0-9]{1,5}$ || ! $key =~ ^[A-Za-z0-9._-]+:[A-Za-z0-9+/]+=*$ ]]; then
        echo "Ignoring ${fields[0]}: its nix-cache offer needs a port and a public-key." >&2
        continue
    fi
    offered[$host]="$port $key"
done <<< "$lines"

if (( ${#offered[@]} == 0 )) && ! $prune; then
    echo "No peer offers a Nix cache right now; leaving $target as it is."
    exit 0
fi

declare -A wanted=()
if ! $prune; then
    for host in "${!approved[@]}"; do wanted[$host]=${approved[$host]}; done
fi
changes=()
for host in "${!offered[@]}"; do
    if [[ ${approved[$host]:-} != "${offered[$host]}" ]]; then
        changes+=("$host  ${offered[$host]% *}  ${offered[$host]#* }${approved[$host]:+   (replaces $(echo "${approved[$host]}" | cut -d' ' -f2))}")
    fi
    wanted[$host]=${offered[$host]}
done

if (( ${#changes[@]} > 0 )); then
    echo "These caches would be trusted to sign packages for this machine:"
    printf '  %s\n' "${changes[@]}"
    if ! $yes; then
        [[ -t 0 && -t 1 ]] || { echo "Run this from a terminal to approve them, or pass --yes." >&2; exit 1; }
        read -r -p "Trust them? [y/N] " answer
        [[ $answer == [yY]* ]] || { echo "Not changed."; exit 1; }
    fi
fi

staged=$(mktemp)
trap 'rm -f -- "$staged"' EXIT
{
    echo "# Generated by scripts/update-nix-cache.sh from the mesh. Run it again instead of editing."
    substituters=() keys=()
    for host in $(printf '%s\n' "${!wanted[@]}" | sort); do
        read -r port key <<< "${wanted[$host]}"
        echo "# peer $host $port $key"
        substituters+=("http://$host:$port")
        keys+=("$key")
    done
    (( ${#substituters[@]} == 0 )) || echo "extra-substituters = ${substituters[*]}"
    (( ${#keys[@]} == 0 )) || echo "extra-trusted-public-keys = ${keys[*]}"
} > "$staged"

if [[ -f $target ]] && cmp -s -- "$staged" "$target"; then
    echo "$target is already up to date."
    exit 0
fi
as_root install -d -m 0755 "$(dirname "$target")"
as_root install -m 0644 -- "$staged" "$target"
echo "Installed $target"
