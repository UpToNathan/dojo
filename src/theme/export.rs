fn json_bytes(value: &Value) -> anyhow::Result<Vec<u8>> {
    let mut bytes = serde_json::to_vec_pretty(value)?;
    bytes.push(b'\n');
    Ok(bytes)
}

fn unpaired_background<'a>(p: &'a SemanticPalette, preferred: &str) -> &'a str {
    let foreground = Rgb::parse(p.color("foreground")).expect("validated palette");
    let muted = Rgb::parse(p.color("foreground_muted")).expect("validated palette");
    let readable = |role| {
        let background = Rgb::parse(p.color(role)).expect("validated palette");
        foreground.contrast(background) >= if p.authored { 3. } else { 4.5 }
            && muted.contrast(background) >= 3.
    };
    for role in [preferred, "surface_raised", "surface", "background"] {
        if readable(role) {
            return p.color(role);
        }
    }
    p.color("background")
}

pub(super) fn render(
    theme: &Theme,
    appearance: Appearance,
) -> anyhow::Result<BTreeMap<String, Vec<u8>>> {
    theme.dark.validate()?;
    theme.light.validate()?;
    let p = theme.palette(appearance);
    let mut out = BTreeMap::new();
    let mut add = |name: &str, contents: Vec<u8>| {
        out.insert(name.to_string(), contents);
    };
    add("palette.json", serde_json::to_vec_pretty(p)?);
    let dojo: serde_json::Map<_, _> = [
        "primary",
        "background",
        "foreground",
        "background_highlight",
        "border",
        "foreground_muted",
        "primary_foreground",
        "selection_foreground",
        "surface",
        "surface_raised",
    ]
    .into_iter()
    .map(|role| (role.to_string(), json!(p.color(role))))
    .collect();
    add("dojo.json", json_bytes(&Value::Object(dojo))?);
    add(
        "nvim.json",
        json_bytes(
            &json!({"appearance":appearance.name(),"preset":theme.preset,"colors":p.colors,"terminal":p.terminal}),
        )?,
    );
    add("kitty.conf", kitty(p).into_bytes());
    add("ghostty.conf", ghostty(p).into_bytes());
    add("niri.kdl", niri(p).into_bytes());
    add("hokum.kdl", hokum(p).into_bytes());
    add("opencode.json", json_bytes(&opencode(theme)?)?);
    add("pi.json", json_bytes(&pi(p))?);
    add(
        "t3code.json",
        json_bytes(
            &json!({"version":1,"name":"Dojo","appearance":appearance.name(),"colors":t3_colors(p),"variants":{"dark":t3_colors(&theme.dark),"light":t3_colors(&theme.light)}}),
        )?,
    );
    add("yazi.toml", yazi(p).into_bytes());
    add("tmtheme.xml", textmate(p).into_bytes());
    add("zen.json", json_bytes(&zen(p))?);
    add("helium.json", json_bytes(&chromium_theme(p))?);
    add("gtk-3.0.css", gtk(p, 3).into_bytes());
    add("gtk-4.0.css", gtk(p, 4).into_bytes());
    add("qt5.conf", qt(p, 21).into_bytes());
    add("qt6.conf", qt(p, 22).into_bytes());
    Ok(out)
}

