fn t3_colors(p: &SemanticPalette) -> Value {
    let groups = [
        (
            "background",
            &["canvas", "chrome", "toolbar", "terminalBackground"] as &[&str],
        ),
        (
            "surface",
            &[
                "surface",
                "secondary",
                "muted",
                "messageSurface",
                "sidebar",
                "codeBackground",
            ],
        ),
        (
            "surface_raised",
            &[
                "surfaceRaised",
                "surfaceOverlay",
                "toolbarControl",
                "sidebarControlSurface",
            ],
        ),
        (
            "foreground",
            &[
                "text",
                "toolbarForeground",
                "toolbarControlForeground",
                "secondaryForeground",
                "messageForeground",
                "sidebarForeground",
                "codeForeground",
                "terminalForeground",
            ],
        ),
        (
            "foreground_muted",
            &[
                "textMuted",
                "mutedForeground",
                "placeholder",
                "secondaryLabel",
                "iconMuted",
                "sidebarMutedForeground",
            ],
        ),
        (
            "border",
            &[
                "border",
                "input",
                "toolbarBorder",
                "sidebarBorder",
                "terminalScrollbar",
            ],
        ),
        (
            "primary",
            &[
                "accent",
                "focus",
                "update",
                "updateForeground",
                "messageAction",
                "terminalCursor",
            ],
        ),
        (
            "primary_foreground",
            &["accentForeground", "messageActionForeground"],
        ),
        (
            "background_highlight",
            &[
                "toolbarControlHover",
                "sidebarRowHover",
                "sidebarRowActive",
                "sidebarRowSelected",
                "terminalSelection",
                "terminalScrollbarHover",
            ],
        ),
        (
            "selection_foreground",
            &["searchMatchForeground", "searchMatchActiveForeground"],
        ),
        (
            "warning",
            &[
                "warning",
                "warningForeground",
                "searchMatchBackground",
                "searchMatchActiveBackground",
            ],
        ),
        ("error", &["error", "errorForeground"]),
        ("diff_removed_background", &["errorSurface"]),
        ("surface", &["warningSurface"]),
        ("surface", &["updateSurface"]),
    ];
    let mut colors = serde_json::Map::new();
    for (role, keys) in groups {
        for key in keys {
            colors.insert((*key).into(), json!(p.color(role)));
        }
    }
    for (role, foreground, surface, fallback) in [
        ("warning", "warningForeground", "warningSurface", "surface"),
        (
            "error",
            "errorForeground",
            "errorSurface",
            "diff_removed_background",
        ),
    ] {
        if p.colors.contains_key(&format!("{role}_background")) {
            colors.insert(foreground.into(), json!(p.color(role)));
            colors.insert(
                surface.into(),
                json!(p.color_or(&format!("{role}_background"), fallback)),
            );
        }
    }
    for role in [
        "toolbarControlHover",
        "sidebarRowHover",
        "sidebarRowActive",
        "sidebarRowSelected",
        "terminalSelection",
        "terminalScrollbarHover",
    ] {
        let preferred = if role.ends_with("Hover") && p.colors.contains_key("background_hover") {
            "background_hover"
        } else {
            "background_highlight"
        };
        colors.insert(role.into(), json!(unpaired_background(p, preferred)));
    }
    for role in ["searchMatchForeground", "searchMatchActiveForeground"] {
        let foreground = super::readable(
            Rgb::parse(p.color("selection_foreground")).expect("validated palette"),
            Rgb::parse(p.color("warning")).expect("validated palette"),
            4.5,
        );
        colors.insert(role.into(), json!(foreground.hex()));
    }
    let parse = |role: &str| Rgb::parse(p.color(role)).expect("validated palette");
    // T3 Code draws its ordinary text and icons on `accentSurface` (a selected toolbar toggle, a chip),
    // so it has to be a background those are readable on. The selection colour is often the text colour
    // itself, which left the icon invisible on a pale pill. Tint the surface toward the accent instead,
    // so it still reads as selected, and say which foreground goes with it.
    let accent_surface = super::blend(parse("surface_raised"), parse("primary"), 0.25);
    let accent_surface = if parse("foreground").contrast(accent_surface) >= 4.5 { accent_surface } else { Rgb::parse(unpaired_background(p, "surface_raised")).expect("validated palette") };
    colors.insert("accentSurface".into(), json!(accent_surface.hex()));
    colors.insert("accentSurfaceForeground".into(), json!(super::readable(parse("foreground"), accent_surface, 4.5).hex()));
    // The hover of the accent-coloured action button: the accent a little lighter, while the button's own
    // text stays readable on it.
    let button_text = parse("primary_foreground");
    let hover = super::blend(parse("primary"), parse("foreground"), 0.18);
    let hover = if button_text.contrast(hover) >= 4.5 { hover } else { parse("primary") };
    colors.insert("messageActionHover".into(), json!(hover.hex()));
    Value::Object(colors)
}

