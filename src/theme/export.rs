fn textmate(p: &SemanticPalette) -> String {
    let mut xml = format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?><!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\"><plist version=\"1.0\"><dict><key>name</key><string>Dojo</string><key>settings</key><array><dict><key>settings</key><dict><key>background</key><string>{}</string><key>foreground</key><string>{}</string></dict></dict>",
        p.color("background"),
        p.color("foreground")
    );
    for (scope, role) in [
        ("comment", "foreground_muted"),
        ("keyword, storage", "secondary"),
        ("entity.name.function", "primary"),
        ("string", "success"),
        ("constant.numeric", "warning"),
        ("entity.name.type, support.type", "info"),
        ("invalid, markup.deleted", "error"),
        ("markup.inserted", "success"),
        ("variable", "foreground"),
    ] {
        let color = match scope {
            "comment" => p.syntax("comment"),
            "keyword, storage" => p.syntax("keyword"),
            "entity.name.function" => p.syntax("function"),
            "string" => p.syntax("string"),
            "constant.numeric" => p.syntax("number"),
            "entity.name.type, support.type" => p.syntax("type"),
            "variable" => p.syntax("variable"),
            _ => p.color(role),
        };
        xml.push_str(&format!("<dict><key>scope</key><string>{scope}</string><key>settings</key><dict><key>foreground</key><string>{color}</string></dict></dict>"));
    }
    xml.push_str("</array></dict></plist>\n");
    xml
}

fn zen(p: &SemanticPalette) -> Value {
    let pairs = [
        ("frame", "background"),
        ("frame_inactive", "surface"),
        ("tab_background_text", "foreground"),
        ("tab_selected", "surface_raised"),
        ("tab_text", "foreground"),
        ("toolbar", "background"),
        ("toolbar_text", "foreground"),
        ("toolbar_field", "background"),
        ("toolbar_field_text", "foreground"),
        ("toolbar_field_border", "border"),
        ("toolbar_field_focus", "surface_raised"),
        ("toolbar_field_text_focus", "foreground"),
        ("toolbar_field_border_focus", "primary"),
        ("toolbar_top_separator", "border"),
        ("toolbar_bottom_separator", "border"),
        ("toolbar_vertical_separator", "border"),
        ("popup", "surface"),
        ("popup_text", "foreground"),
        ("popup_border", "border"),
        ("popup_highlight", "background_highlight"),
        ("popup_highlight_text", "selection_foreground"),
        ("sidebar", "surface"),
        ("sidebar_text", "foreground"),
        ("sidebar_border", "border"),
        ("sidebar_highlight", "background_highlight"),
        ("sidebar_highlight_text", "selection_foreground"),
        ("icons", "foreground"),
        ("icons_attention", "primary"),
        ("button_background_hover", "background_highlight"),
        ("button_background_active", "surface_raised"),
    ];
    let colors: serde_json::Map<_, _> = pairs
        .into_iter()
        .map(|(token, role)| {
            (
                token.into(),
                json!(if token == "button_background_hover" {
                    unpaired_background(p, role)
                } else {
                    p.color(role)
                }),
            )
        })
        .collect();
    json!({"colors":colors,"properties":{"color_scheme":p.appearance.name(),"content_color_scheme":p.appearance.name()}})
}

fn gtk(p: &SemanticPalette, version: u8) -> String {
    let mut css =
        String::from("/* Generated Dojo named-theme palette. Not a global gtk.css override. */\n");
    let base = if version == 3 {
        if p.appearance == Appearance::Dark {
            "Adwaita/gtk-contained-dark.css"
        } else {
            "Adwaita/gtk-contained.css"
        }
    } else if p.appearance == Appearance::Dark {
        "Default/Default-dark.css"
    } else {
        "Default/Default-light.css"
    };
    css.push_str(&format!(
        "@import url(\"resource:///org/gtk/libgtk/theme/{base}\");\n"
    ));
    for (name, role) in [
        ("theme_bg_color", "background"),
        ("theme_fg_color", "foreground"),
        ("theme_base_color", "surface"),
        ("theme_text_color", "foreground"),
        ("theme_selected_bg_color", "primary"),
        ("theme_selected_fg_color", "primary_foreground"),
        ("borders", "border"),
        ("insensitive_fg_color", "foreground_muted"),
        ("warning_color", "warning"),
        ("error_color", "error"),
        ("success_color", "success"),
        ("accent_bg_color", "primary"),
        ("accent_fg_color", "primary_foreground"),
        ("window_bg_color", "background"),
        ("window_fg_color", "foreground"),
        ("view_bg_color", "surface"),
        ("view_fg_color", "foreground"),
    ] {
        css.push_str(&format!("@define-color {name} {};\n", p.color(role)));
    }
    css.push_str("window, dialog, .background { background-color: @theme_bg_color; color: @theme_fg_color; }\nheaderbar, toolbar, popover, menu, menubar { background-color: @theme_base_color; color: @theme_fg_color; border-color: @borders; }\nbutton, entry, textview, list, treeview, columnview { background-color: @theme_base_color; color: @theme_text_color; border-color: @borders; }\nbutton:hover, row:hover { background-color: @theme_selected_bg_color; color: @theme_selected_fg_color; }\n*:selected, selection { background-color: @theme_selected_bg_color; color: @theme_selected_fg_color; }\n*:disabled { color: @insensitive_fg_color; }\n.error { color: @error_color; }\n.warning { color: @warning_color; }\n.success { color: @success_color; }\n");
    css
}

fn qt(p: &SemanticPalette, count: usize) -> String {
    let roles = [
        "foreground",
        "surface",
        "surface_raised",
        "surface_raised",
        "background",
        "border",
        "foreground",
        "foreground",
        "foreground",
        "background",
        "surface",
        "border",
        "primary",
        "primary_foreground",
        "info",
        "secondary",
        "surface_raised",
        "background",
        "surface_raised",
        "foreground",
        "foreground_muted",
        "primary",
    ];
    let active: Vec<_> = roles[..count].iter().map(|role| p.color(role)).collect();
    let mut disabled = active.clone();
    for index in [0, 6, 7, 8, 19] {
        disabled[index] = p.color("foreground_muted");
    }
    format!(
        "[ColorScheme]\nactive_colors={}\ninactive_colors={}\ndisabled_colors={}\n",
        active.join(", "),
        active.join(", "),
        disabled.join(", ")
    )
}

